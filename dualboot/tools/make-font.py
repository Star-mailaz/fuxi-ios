#!/usr/bin/env python3
"""Generate the exact monochrome subset used by the native boot menu.

Requires Pillow. Source font: Google Fonts Noto Sans TC, SIL OFL 1.1.
Pass a local TTF; this script never downloads or accesses a phone.
"""
import argparse
import hashlib
import re
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    chars = set(chr(n) for n in range(32, 127))
    for name in ("render.c", "board.c"):
        source = (root / name).read_text(encoding="utf-8")
        for literal in re.findall(r'"([^"\n]*)"', source):
            chars.update(ch for ch in literal if ord(ch) >= 0x3000)
    source_sha = hashlib.file_digest(args.font.open("rb"), "sha256").hexdigest()
    if source_sha != "864727d210d54f2537bbe23b3a839436c3992af72de9322af5270897246bd44f":
        raise ValueError("Expected the pinned OFL Noto Sans TC font; SHA256 differs")
    font = ImageFont.truetype(str(args.font), 48)
    font.set_variation_by_axes([400])
    lines = [
        "/* Generated by tools/make-font.py; glyph data: SIL-OFL-1.1.",
        " * Noto Sans TC, Google Fonts commit 3be1884c48c3e45b52ecc725676a08f87776373e.",
        " * 48 px, weight 400, monochrome 64x64 cells.",
        f" * Font SHA256: {source_sha}. See licenses/NotoSansTC-OFL.txt. */",
        "#ifndef FUXI_MENU_FONT_GENERATED_H",
        "#define FUXI_MENU_FONT_GENERATED_H",
        "struct menu_glyph { uint32_t code; unsigned advance; unsigned char bits[512]; };",
        f"#define MENU_GLYPH_COUNT {len(chars)}u",
        "static const struct menu_glyph menu_glyphs[MENU_GLYPH_COUNT] = {",
    ]
    for ch in sorted(chars):
        image = Image.new("1", (64, 64))
        ImageDraw.Draw(image).text((0, 52), ch, font=font, fill=1, anchor="ls", stroke_width=0)
        advance = round(font.getlength(ch))
        if advance > 64 or advance < 1:
            raise ValueError(f"Glyph does not fit: {ch!r}")
        data = image.tobytes()
        lines.append(f"    {{0x{ord(ch):04x}, {advance}, {{")
        for row in range(0, len(data), 32):
            lines.append("        " + ",".join(f"0x{x:02x}" for x in data[row:row + 32]) + ",")
        lines.append("    }},")
    lines.extend(["};", "#endif", ""])
    (root / "font-generated.h").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Generated {len(chars)} glyphs, font sha256 {source_sha}")


if __name__ == "__main__":
    main()
